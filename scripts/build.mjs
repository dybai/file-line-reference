// Stitch the browser bundle: src/flr-core.cjs body + src/main.js into client.js.
// Edit sources and rebuild; never edit client.js directly.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const core = readFileSync(join(root, 'src/flr-core.cjs'), 'utf8');
const main = readFileSync(join(root, 'src/main.js'), 'utf8');

const BEGIN = '/* FLR_CORE_BEGIN */';
const END = '/* FLR_CORE_END */';
const begin = core.indexOf(BEGIN);
const end = core.indexOf(END);
if (begin < 0 || end < 0 || end < begin) throw new Error('flr-core.cjs: FLR_CORE markers missing');
const coreBody = core.slice(begin + BEGIN.length, end);

const header = [
	'/* Generated by scripts/build.mjs from src/ — do not edit. */',
	"window.__ModuleLoader__.load({",
	"\tid: '@dybai/file-line-reference',",
	"\tfactory(require) {",
	// __ModuleLoader__ calls factory(require) with only `require`; `module`/`exports`
	// are NOT injected. Bundles must create their own CJS face (as official bundles do).
	'\t\tvar module = { exports: {} };',
	'\t\tvar exports = module.exports;',
	'\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });',
	'\t\tconst FlrCore = (function () {',
	coreBody,
	'\t\t})();',
	''
].join('\n');
const footer = [
	'',
	'\t\texports.apply = apply;',
	'\t\texports.inject = inject;',
	'\t\treturn module.exports;',
	'\t}',
	'});',
	''
].join('\n');

writeFileSync(join(root, 'client.js'), header + main + footer);
console.log('client.js written');
